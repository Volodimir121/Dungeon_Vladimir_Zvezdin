#pragma once
#include "Creature.h"

class Map;

/*
 * Класс Hero — герой подземелья, наследник Creature (практика 12, задание 3).
 *
 * Практика 9, задание 3: методы move, takeDamage (унаследован), printStatus.
 * Практика 10, задание 5: конструктор по умолчанию, конструктор с параметрами,
 *                         деструктор с логированием времени жизни.
 *
 * ИНВАРИАНТ КЛАССА (практика 11, критерий 1):
 *   все утверждения инварианта Creature (0 <= health <= maxHealth, maxHealth > 0,
 *   координаты неотрицательны), а также:
 *   — символ героя всегда '@';
 *   — после любого вызова move() герой стоит на клетке, которую карта разрешила
 *     (map.canEnter == true); при отказе карты позиция не меняется;
 *   — gold не переполняется: addGold насыщает значение на максимуме unsigned int.
 * Все поля закрыты. Задать герою здоровье извне можно только уменьшив его
 * через takeDamage(); сеттеров нет вообще, потому что без них можно обойтись.
 */
class Hero : public Creature
{
public:
    /* Урон героя по монстру при атаке (ход в клетку с монстром) */
    static constexpr int ATTACK_DAMAGE = 25;

    /* Практика 10, задание 5: герой в точке (1, 1) с полным здоровьем */
    Hero();

    /*
     * Практика 10, задание 5: начальные координаты, здоровье и золото.
     * При startHealth <= 0 или отрицательных координатах бросает std::invalid_argument
     * (проверка в конструкторе Creature).
     */
    Hero(int startX, int startY, int startHealth = 100, unsigned int startGold = 0);

    /* Практика 10, задание 3: деструктор логирует уничтожение (виртуальный, т.к. базовый виртуальный) */
    ~Hero() override;

    unsigned int getGold() const;

    /*
     * Переместиться в направлении (dx, dy), если карта разрешает войти в клетку.
     * Герой не хранит карту и не лезет в её данные, а лишь задаёт ей вопрос
     * map.canEnter(nx, ny).
     */
    bool move(int dx, int dy, const Map& map);

    /* Добавить золото (с насыщением при переполнении) */
    void addGold(unsigned int amount = 1);

    /* Вывести текущее состояние героя на экран */
    void printStatus() const;

    /*
     * Ход героя определяется командой игрока и выполняется в Game::processCommand,
     * поэтому «автоматического» хода у героя нет: метод ничего не делает.
     */
    void takeTurn(IWorld& world) override;

    std::string getName() const override;

private:
    unsigned int gold;
};
