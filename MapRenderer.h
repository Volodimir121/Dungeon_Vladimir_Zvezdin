#pragma once
#include <vector>

class Map;
class Creature;

/*
 * Класс MapRenderer — отрисовка карты (практика 11, задание 5).
 *
 * Принцип единственной ответственности: Map хранит данные, MapRenderer их показывает.
 * Рендерер получает карту и список существ только для чтения (const) и работает
 * исключительно через публичные геттеры Map (getRows, getCols, getCell), поэтому
 * «потрохов» карты он не видит, и разделение не фиктивное: дружественных
 * классов и открытых полей нет.
 *
 * ИНВАРИАНТ КЛАССА: объект не имеет состояния, ничего не меняет в карте и
 * существах; draw() рисует только живых существ, лежащих в границах карты.
 */
class MapRenderer
{
public:
    /* Вывести карту; существа рисуются поверх клеток, позднее в списке — выше */
    void draw(const Map& map, const std::vector<const Creature*>& creatures) const;
};
